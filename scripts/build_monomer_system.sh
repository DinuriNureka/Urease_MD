#!/usr/bin/env bash
# scripts/build_monomer_system.sh
# -------------------------------------------------------
# Build one solvated AMBER system for the monomer heterodimer.
#
# This replaces the old full-dodecamer logic:
# - No 12-site loops
# - One active site patch/bond set only
# - Uses monomer-specific Ni center bond/patch snippets
#
# Usage:
#   bash scripts/build_monomer_system.sh mol01_pose01_monomer
#
# Inputs (expected):
#   systems/<name>/complex.pdb
#     - monomer protein (chains B+Q) with inhibitor pose already placed
#   params/ni_center/mcpb_input/*
#   params/ni_center/monomer/bonds_monomer.txt
#   params/ni_center/monomer/set_patch_monomer.txt
#   params/inhibitors/mol2/<inhib>_gaff2.mol2
#   params/inhibitors/frcmod/<inhib>.frcmod
#
# Outputs:
#   systems/<name>/monomer_<inhib>.prmtop
#   systems/<name>/monomer_<inhib>.inpcrd
#   systems/<name>/solvated_hmr.prmtop (HMR-derived topology for 4 fs)
#   systems/<name>/solvated_hmr.rst7   (coords consistent with the HMR topology)
# -------------------------------------------------------
set -euo pipefail
source "$(dirname "$0")/../config.env"

NAME=${1:?"Usage: bash build_monomer_system.sh <system_name>"}

INHIB="$(echo "${NAME}" | sed -E 's/_pose[0-9]*//; s/_monomer$//')"
SDIR="${PROJECT_ROOT}/systems/${NAME}"

# Monomer Ni center assets
KCX_MOL2="${PROJECT_ROOT}/params/ni_center/mcpb_input/KCX_full_stopgap.mol2"
OHB_MOL2="${PROJECT_ROOT}/params/ni_center/mcpb_input/OHB.mol2"
KCX_FRCMOD="${PROJECT_ROOT}/params/ni_center/mcpb_input/KCX.frcmod"
OHB_FRCMOD="${PROJECT_ROOT}/params/ni_center/mcpb_input/OHB.frcmod"
UREASE_FRCMOD="${PROJECT_ROOT}/params/ni_center/mcpb_input/urease_mcpbpy.frcmod"

MON_BONDS="${PROJECT_ROOT}/params/ni_center/monomer/bonds_monomer.txt"
MON_PATCH="${PROJECT_ROOT}/params/ni_center/monomer/set_patch_monomer.txt"

# Inhibitor assets (GAFF2); optional charge-corrected mol2 override
IMOL="${PROJECT_ROOT}/params/inhibitors/mol2/${INHIB}_gaff2.mol2"
if [[ -n "${LIGAND_MOL2_OVERRIDE:-}" && -f "${LIGAND_MOL2_OVERRIDE}" ]]; then
  IMOL="${LIGAND_MOL2_OVERRIDE}"
elif [[ -f "${PROJECT_ROOT}/params/inhibitors/mol2/${INHIB}_chargecorrected.mol2" ]]; then
  IMOL="${PROJECT_ROOT}/params/inhibitors/mol2/${INHIB}_chargecorrected.mol2"
fi
IFRC="${PROJECT_ROOT}/params/inhibitors/frcmod/${INHIB}.frcmod"

# This file is protein-only; we reuse a validated reference build.
# Override via env var if you have a better per-project reference.
PROVISIONAL_AUTOPATCH_FRCMOD="${PROVISIONAL_AUTOPATCH_FRCMOD:-${PROJECT_ROOT}/systems/mol6_pose2_full/provisional_autopatch_optB.frcmod}"

if [[ ! -f "${SDIR}/complex.pdb" ]]; then
  echo "[FAIL] Missing: ${SDIR}/complex.pdb"
  echo "       build_monomer_system.sh expects a pose-placed monomer complex.pdb."
  exit 1
fi

for f in "${KCX_MOL2}" "${OHB_MOL2}" "${KCX_FRCMOD}" "${OHB_FRCMOD}" "${UREASE_FRCMOD}" \
         "${MON_BONDS}" "${MON_PATCH}" "${IMOL}" "${IFRC}" "${PROVISIONAL_AUTOPATCH_FRCMOD}"; do
  [[ -f "$f" ]] || { echo "[FAIL] Missing: $f"; exit 1; }
done

log() { echo "[$(date '+%H:%M:%S')] $1"; }

log "Building monomer system: ${NAME} (inhibitor: ${INHIB})"
log "Active site patch: one site only"
log "Expected Ni residue numbers in the un-solvated unit: NI at mol.1046 & mol.1047; OHB at mol.1048"
log "Solvation: TIP3PBOX, truncated octahedron, ${BOX_BUFFER} A buffer"

TLEAP_IN="${SDIR}/tleap_monomer.in.generated"
TLEAP_LOG="${SDIR}/tleap_monomer.log"

cat > "${TLEAP_IN}" << TLEAPEOF
# ============================================================
# tleap (monomer): ${NAME}
# Generated by build_monomer_system.sh — do not edit manually
# ============================================================

# Force fields
source ${PROTEIN_FF}
source ${LIGAND_FF}
source ${WATER_FF}

# Ni center atom types referenced by the monomer patch files
addAtomTypes {
        { "M1"  "Ni" "sp3" }
        { "M2"  "Ni" "sp3" }
        { "Y1"  "O"  "sp3" }
        { "Y2"  "N"  "sp3" }
        { "Y3"  "N"  "sp3" }
        { "Y4"  "O"  "sp3" }
        { "Y5"  "N"  "sp3" }
        { "Y6"  "N"  "sp3" }
        { "Y7"  "O"  "sp3" }
        { "Y8"  "O"  "sp3" }
}

# Ni center parameters
KCX = loadmol2 ${KCX_MOL2}
OHB = loadmol2 ${OHB_MOL2}
loadamberparams ${KCX_FRCMOD}
loadamberparams ${OHB_FRCMOD}
loadamberparams ${UREASE_FRCMOD}
# Protein-only provisional autopatch FR KCN/dihedral/etc assets (validated on mol6_pose2_full)
loadamberparams ${PROVISIONAL_AUTOPATCH_FRCMOD}

# Inhibitor parameters (types/charges needed for complex.pdb's LIG residue)
loadamberparams ${IFRC}
LIG = loadmol2 ${IMOL}

# Load the already pose-placed monomer complex
mol = loadpdb ${SDIR}/complex.pdb

# Metal-ligand bonds / Ni center patching (ONE active site only)
source ${MON_BONDS}
source ${MON_PATCH}

# Check before solvation
check mol

# Solvate: rectangular box (solvatebox) or truncated octahedron (solvateoct)
if [[ "${BOX_TYPE:-rectangular}" == "rectangular" ]]; then
  solvatebox mol ${WATER_BOX} ${BOX_BUFFER}
else
  solvateoct mol ${WATER_BOX} ${BOX_BUFFER}
fi

# Neutralize
addions mol Na+ 0
addions mol Cl- 0

# Salt (physiological NaCl). For the monomer box sizes, 140/140 is a reasonable starting estimate.
# If you want strictness, we can compute ion counts from water number after solvation.
addionsrand mol Na+ 140 Cl- 140

# Save
saveamberparm mol ${SDIR}/monomer_${INHIB}.prmtop ${SDIR}/monomer_${INHIB}.inpcrd
savepdb mol ${SDIR}/monomer_${INHIB}.pdb

quit
TLEAPEOF

tleap -f "${TLEAP_IN}" > "${TLEAP_LOG}" 2>&1
if grep -qi "error\|fatal\|could not" "${TLEAP_LOG}"; then
  log "[FAIL] tleap errors — check ${TLEAP_LOG}"
  grep -i "error\|fatal" "${TLEAP_LOG}" || true
  exit 1
fi

# Ni/KCX/OHB: tLeap can leave non-contiguous atoms in one "molecule"; fix before HMR / MD.
CPPTRAJ="${CPPTRAJ:-/usr/local/bin/cpptraj}" bash "${PROJECT_ROOT}/scripts/fix_atomorder_amber.sh" \
  "${SDIR}/monomer_${INHIB}.prmtop" "${SDIR}/monomer_${INHIB}.inpcrd" || {
  log "[FAIL] fixatomorder — check cpptraj and topology"
  exit 1
}

log "Applying HMR..."
python3 -c "
import parmed as pmd
p = pmd.load_file('${SDIR}/monomer_${INHIB}.prmtop', '${SDIR}/monomer_${INHIB}.inpcrd')
pmd.tools.HMassRepartition(p).execute()
p.save('${SDIR}/solvated_hmr.prmtop', overwrite=True)
p.save('${SDIR}/solvated_hmr.rst7', overwrite=True)
" || { log "[FAIL] HMR generation failed"; exit 1; }

log "[OK] ${NAME}: built monomer topology + HMR"

