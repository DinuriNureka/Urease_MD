#!/usr/bin/env bash
# ============================================================
# MD pipeline visualization & QC checkpoints (reference commands)
# Run individual sections as needed: bash scripts/visualize_checkpoints.sh [NAME] [LIGNAME]
# ============================================================
set -euo pipefail
SCRIPT_ROOT="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=/dev/null
source "${SCRIPT_ROOT}/../config.env"

NAME="${1:-mol6_pose2_monomer}"
LIGNAME="${2:-mol6}"
SYS="${PROJECT_ROOT}/systems/${NAME}"
SIM="${PROJECT_ROOT}/simulations/${NAME}"
PRMTOP="${SYS}/monomer_${LIGNAME}.prmtop"
HMR_PRMTOP="${SYS}/solvated_hmr.prmtop"

echo "============================================"
echo "  1. ESP / RESP charge visualization"
echo "============================================"
echo ""
echo "--- Generate ESP cube from ORCA .gbw ---"
echo "  orca_2mkl <basename> -molden"
echo "  Then in Multiwfn:"
echo "    multiwfn <basename>.molden.input"
echo "    Menu: 5 → 12 → 1 → 0 → 0 → q"
echo "    Exports .cub file"
echo ""
echo "--- View ESP surface ---"
echo "  VMD:  vmd <name>.cub"
echo "    Graphics → Representations → Drawing Method: Isosurface"
echo "    Coloring: Volume"
echo "  Jmol: jmol <name>.cub"
echo "    Console: isosurface vdw map <name>_esp.cub"
echo ""
echo "--- RESP accuracy ---"
echo "  Multiwfn RRMS between RESP-fitted and QM ESP"
echo "  Current project mean RMSE: ~0.004 e (approved)"
echo ""

echo "============================================"
echo "  2. Minimization check"
echo "============================================"
echo ""
echo "  Check energy convergence:"
echo "    tail -30 ${SIM}/min1/min1.out"
echo "    tail -30 ${SIM}/min2/min2.out"
echo ""
echo "  Visual check (convert rst7 to PDB):"
echo "    cpptraj -p ${PRMTOP} <<EOF"
echo "trajin ${SIM}/min2/min2.rst7"
echo "trajout /tmp/min2_check.pdb pdb"
echo "run"
echo "quit"
echo "EOF"
echo "    vmd /tmp/min2_check.pdb"
echo ""

echo "============================================"
echo "  3. Equilibration spot-checks"
echo "============================================"
echo ""
echo "  Temperature (should be ~300 K after heating):"
echo "    grep 'TEMP(K)' ${SIM}/equil1/equil1.out | tail -5"
echo "    grep 'TEMP(K)' ${SIM}/equil_free/equil_free.out | tail -5"
echo ""
echo "  Density (should be ~1.0 g/cm³):"
echo "    grep -i density ${SIM}/equil1/equil1.out | tail -5"
echo "    grep -i density ${SIM}/equil_free/equil_free.out | tail -5"
echo ""
echo "  Trajectory in VMD:"
echo "    vmd ${PRMTOP} ${SIM}/equil1/equil1.nc"
echo ""

echo "============================================"
echo "  4. Production spot-checks"
echo "============================================"
echo ""
echo "  Load in VMD:"
echo "    vmd ${HMR_PRMTOP} ${SYS}/prod_rep01/prod.nc"
echo "    Check: protein fold, ligand in pocket, no vacuum bubbles"
echo ""
echo "  Quick backbone RMSD (adjust :1-810 to your solute range):"
echo "    cpptraj -p ${HMR_PRMTOP} <<'CPPIN'"
echo "trajin ${SYS}/prod_rep01/prod.nc"
echo "rms first :1-810@CA out /tmp/rmsd_rep01.dat"
echo "run"
echo "quit"
echo "CPPIN"
echo "    echo 'RMSD should plateau, not drift.'"
echo ""
echo "  Compare replicates:"
echo "    for REP in 01 02 03; do"
echo "      cpptraj -p ${HMR_PRMTOP} <<CPPIN"
echo "trajin ${SYS}/prod_rep\${REP}/prod.nc"
echo "rms first :1-810@CA out /tmp/rmsd_rep\${REP}.dat"
echo "run"
echo "quit"
echo "CPPIN"
echo "    done"
echo ""
