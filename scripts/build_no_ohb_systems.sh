#!/usr/bin/env bash
# Build five monomer + ligand systems with no-OHB Ni MCPB parameters.
# Does not modify params/ni_center/ or systems/*_monomer/ (legacy).
#
# Prereqs:
#   - monomer_BQ_apo_no_ohb.pdb = monomer_BQ_apo.pdb with HETATM OHB B9801 removed
#     (grep -v 'OHB B9801') so bridging OH is not in topology.
#   - KCX: use KCX_full_stopgap.mol2 (full residue for PDB) not KX1.mol2 (cluster fragment only).
#   - urease_no_ohb_mcpbpy.frcmod includes DIHE Y7-CO-2C-XC (ASP OD1 Y7) for GAFF2 + leap.
#
set -u
set -o pipefail

PROJECT_ROOT="/path/to/urease_md"
# shellcheck source=/dev/null
source "${PROJECT_ROOT}/config.env"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-1}"
export AMBER="${AMBER:-${PMEMD_CUDA_BIN:-/opt/software/AMBER/pmemd24_cuda128/bin/pmemd.cuda}}"

TLEAP="${TLEAP:-/usr/local/bin/tleap}"
if [[ ! -x "${TLEAP}" ]]; then
  TLEAP="$(command -v tleap)"
fi

MCPB="${PROJECT_ROOT}/params/ni_center_no_ohb/mcpb_input"
BONDS="${PROJECT_ROOT}/params/ni_center_no_ohb/monomer/bonds_monomer_no_ohb.txt"
PATCH="${PROJECT_ROOT}/params/ni_center_no_ohb/monomer/set_patch_monomer_no_ohb.txt"
# Bridging OHB (PDB residue OHB B9801) removed — not used in no-OHB MCPB workflow
MONOMER_PDB="${PROJECT_ROOT}/params/ni_center_no_ohb/monomer/monomer_BQ_apo_no_ohb.pdb"

# addAtomTypes block — must match params/ni_center_no_ohb/mcpb_input/urease_no_ohb_tleap.in
read_atomtypes() { cat <<'ATOMTYPES'
addAtomTypes {
        { "M1"  "Ni" "sp3" }
        { "M2"  "Ni" "sp3" }
        { "Y1"  "O" "sp3" }
        { "Y2"  "N" "sp3" }
        { "Y3"  "N" "sp3" }
        { "Y4"  "N" "sp3" }
        { "Y5"  "N" "sp3" }
        { "Y6"  "O" "sp3" }
        { "Y7"  "O" "sp3" }
}
ATOMTYPES
}

write_tleap() {
  local sys="$1"
  local mol="$2"
  local outdir="${PROJECT_ROOT}/systems/${sys}_monomer_no_ohb"
  local tleap_in="${outdir}/tleap_no_ohb.in"
  local lig_frcmod="${PROJECT_ROOT}/systems/${sys}_full/${sys}.frcmod"
  local patch_frcmod="${PROJECT_ROOT}/systems/${sys}_full/provisional_autopatch_optB.frcmod"
  local lig_mol2="${PROJECT_ROOT}/params/inhibitors/mol2/${mol}_gaff2.mol2"

  mkdir -p "${outdir}"

  {
    echo "# no-OHB monomer build — ${sys} — generated by build_no_ohb_systems.sh"
    echo "# PROJECT_ROOT=${PROJECT_ROOT}"
    echo "source leaprc.protein.ff19SB"
    echo "source leaprc.gaff2"
    echo "source leaprc.water.tip3p"
    echo ""
    read_atomtypes
    echo ""
    echo "HD1 = loadmol2 ${MCPB}/HD1.mol2"
    echo "HD2 = loadmol2 ${MCPB}/HD2.mol2"
    echo "# Full KCX residue (backbone + carbamate); OQ1/OQ2 retyped to Y6/Y1 via set_patch"
    echo "KCX = loadmol2 ${MCPB}/KCX_full_stopgap.mol2"
    echo "HE1 = loadmol2 ${MCPB}/HE1.mol2"
    echo "HD3 = loadmol2 ${MCPB}/HD3.mol2"
    echo "AP1 = loadmol2 ${MCPB}/AP1.mol2"
    echo "N11 = loadmol2 ${MCPB}/N11.mol2"
    echo "N21 = loadmol2 ${MCPB}/N21.mol2"
    echo "loadamberparams ${MCPB}/KCX.frcmod"
    echo "loadamberparams ${MCPB}/urease_no_ohb_mcpbpy.frcmod"
    if [[ -f "${lig_frcmod}" ]]; then
      echo "loadamberparams ${lig_frcmod}"
    else
      echo "# WARNING: missing ${lig_frcmod}"
    fi
    if [[ -f "${patch_frcmod}" ]]; then
      echo "loadamberparams ${patch_frcmod}"
    fi
    echo "LIG = loadmol2 ${lig_mol2}"
    echo "protein = loadpdb ${MONOMER_PDB}"
    echo "mol = combine { protein LIG }"
    echo "check mol"
    echo ""
    echo "source ${BONDS}"
    echo "source ${PATCH}"
    echo ""
    echo "check mol"
    echo "solvateoct mol TIP3PBOX 12.0"
    echo "addionsrand mol Na+ 0"
    echo "addionsrand mol Cl- 0"
    echo "saveamberparm mol ${outdir}/monomer_${mol}.prmtop ${outdir}/monomer_${mol}.inpcrd"
    echo "quit"
  } > "${tleap_in}"

  echo "Wrote ${tleap_in}"
}

run_one() {
  local sys="$1"
  local mol="$2"
  local outdir="${PROJECT_ROOT}/systems/${sys}_monomer_no_ohb"
  local log="${outdir}/tleap_no_ohb.log"

  write_tleap "${sys}" "${mol}"

  echo "=== Running tleap for ${sys} (mol ${mol}) ==="
  "${TLEAP}" -f "${outdir}/tleap_no_ohb.in" > "${log}" 2>&1
  local rc=$?

  if grep -E "^ERROR|Error: |FATAL|Fatal" "${log}" 2>/dev/null | head -5; then
    echo "FAILED (${sys}): tleap exit ${rc}, see errors above in ${log}"
    return 1
  fi
  if [[ "${rc}" -ne 0 ]]; then
    echo "FAILED (${sys}): tleap exit ${rc} — see ${log}"
    return 1
  fi
  if grep -E "Errors = [1-9]" "${log}" 2>/dev/null; then
    echo "FAILED (${sys}): Errors != 0 in ${log}"
    return 1
  fi
  echo "PASSED (${sys})"
  return 0
}

main() {
  echo "AMBER (pmemd.cuda) reference: ${AMBER}"
  echo "CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES}"
  echo ""

  local failed=0
  run_one mol1_pose2 mol1 || failed=1
  run_one mol2_pose4 mol2 || failed=1
  run_one mol3_pose1 mol3 || failed=1
  run_one mol4_pose3 mol4 || failed=1
  run_one mol5_pose2 mol5 || failed=1

  echo ""
  echo "=== prmtop sizes ==="
  for sys in mol1_pose2 mol2_pose4 mol3_pose1 mol4_pose3 mol5_pose2; do
    local d="${PROJECT_ROOT}/systems/${sys}_monomer_no_ohb"
    ls -lh "${d}"/monomer_mol*.prmtop 2>/dev/null || echo "(none in ${d})"
  done

  if [[ "${failed}" -ne 0 ]]; then
    echo ""
    echo "One or more builds failed (see logs under systems/*_monomer_no_ohb/)."
    exit 1
  fi
  exit 0
}

main "$@"
